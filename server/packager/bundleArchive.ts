import AdmZip from "adm-zip";
import fs from "node:fs";
import path from "node:path";

// Basically a small reimplementation of bundle.cmake

const BUNDLE_VENDOR_DIR = path.join(
  process.cwd(),
  "server",
  "packager",
  "bundle-vendor",
);
const TEMPLATES_DIR = path.join(BUNDLE_VENDOR_DIR, "templates");
export const BUNDLE_RUNTIME_INCLUDE_DIR = path.join(
  BUNDLE_VENDOR_DIR,
  "runtime",
);

export type BundleOS = "unix" | "macos" | "windows" | "wasm";

const TEMPLATE_FILES: Record<BundleOS, string> = {
  unix: "incbin_unix.S.in",
  macos: "incbin_macos.S.in",
  windows: "incbin_windows.S.in",
  wasm: "incbin_wasm.S.in",
};

export interface BundleFileEntry {
  real: string;
  virtual: string;
}

export interface PrepareBundleSourcesOptions {
  name: string;
  files: BundleFileEntry[];
  compression: "store" | "deflate";
  os: BundleOS;
  workDir: string;
}

export interface PreparedBundleSources {
  pakFile: string;
  asmFile: string;
  cFile: string;
}

export const prepareBundleSources = (
  opts: PrepareBundleSourcesOptions,
): PreparedBundleSources => {
  const { name, files, compression, os, workDir } = opts;
  if (files.length === 0) {
    throw new Error(`prepareBundleSources(${name}): no files given`);
  }

  fs.mkdirSync(workDir, { recursive: true });

  const pakFile = path.join(workDir, `${name}.pak`);
  writePak(pakFile, files, compression);

  const { asmFile, cFile } = generateSources(name, os, pakFile, workDir);

  return { pakFile, asmFile, cFile };
};

const writePak = (
  pakFile: string,
  files: BundleFileEntry[],
  compression: "store" | "deflate",
): void => {
  const zip = new AdmZip();
  for (const file of files) {
    const buf = fs.readFileSync(file.real);
    const entry = zip.addFile(file.virtual, buf);
    if (compression === "store") {
      entry.header.method = 0;
    }
  }
  if (fs.existsSync(pakFile)) fs.rmSync(pakFile);
  zip.writeZip(pakFile);
};

const generateSources = (
  name: string,
  os: BundleOS,
  pakFile: string,
  outputDir: string,
): { asmFile: string; cFile: string } => {
  const templatePath = path.join(TEMPLATES_DIR, TEMPLATE_FILES[os]);
  let asmContent = fs.readFileSync(templatePath, "utf8");
  asmContent = asmContent.replaceAll("%%NAME%%", name).replaceAll(
    "%%PAK_FILE%%",
    path.basename(pakFile),
  );
  if (os === "wasm") {
    const size = fs.statSync(pakFile).size;
    asmContent = asmContent.replaceAll("%%PAK_SIZE%%", size.toString());
  }

  const asmFile = path.join(outputDir, `${name}_data.S`);
  fs.writeFileSync(asmFile, asmContent);

  const cContent =
    `/* Generated by ScratchBox's bundle.cmake reimplementation. Do not edit by hand. */

#include "bundle_runtime.h"

extern const unsigned char bundle_${name}_data[];
extern const unsigned char bundle_${name}_data_end[];

bundle_archive bundle_${name}_archive(void) {
  bundle_archive archive;
  archive.data = bundle_${name}_data;
  archive.size = (size_t)(bundle_${name}_data_end - bundle_${name}_data);
  return archive;
}
`;
  const cFile = path.join(outputDir, `${name}_archive.c`);
  fs.writeFileSync(cFile, cContent);

  return { asmFile, cFile };
};
